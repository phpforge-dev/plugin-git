import {test} from 'node:test';
import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {Window} from 'happy-dom';
import {mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';

test('staged context, editable suggestion, stale index and draft preservation', async () => {
 const folder = await mkdtemp(join(tmpdir(), 'commit-ai-'));
 const output = join(folder, 'test.mjs');
 await build({stdin:{contents:"export {mountCommitGeneration} from './src/git-generate-message'; export {configure} from './src/sdk';",resolveDir:process.cwd()},outfile:output,bundle:true,format:'esm'});
 const {mountCommitGeneration, configure} = await import(pathToFileURL(output));
 const w = new Window();
 globalThis.document = w.document;
 document.body.innerHTML = '<section><textarea id="git-message">draft</textarea></section>';
 const cleanups = [];
 let resolve, prompt, token = 'index-1', diffCalls = [], updates = 0;
 configure({own:fn=>cleanups.push(fn),tr:s=>s,html:s=>s,activeLanguage:()=> 'en',service:()=>({generate:text=>{prompt=text;return new Promise(r=>resolve=r);},cancel:async()=>{}})});
 const api = {gitStatus:async()=>({indexToken:token,changes:[{path:'selected.php',index:'M',worktree:'M'},{path:'excluded.php',index:' ',worktree:'M'}]}),gitDiff:async(path,staged)=>{diffCalls.push([path,staged]);return {before:'old staged',after:'new staged'};}};
 const panel = document.querySelector('section');
 const message = document.querySelector('#git-message');
 const controller = mountCommitGeneration(api,panel,()=>updates++);
 const generate = panel.querySelector('button');
 const dialog = document.querySelector('dialog');
 // happy-dom does not implement nonmodal dialog.show().
 dialog.show = () => {dialog.open = true;};
 dialog.close = () => {dialog.open = false;};
 const apply = dialog.querySelector('[data-apply]');
 const preview = dialog.querySelector('textarea');
 const wait = async () => {for(let i=0;i<20;i++)await Promise.resolve();};
 generate.click();await wait();
 assert.deepEqual(diffCalls,[['selected.php',true]]);
 assert.match(prompt,/new staged/);assert.doesNotMatch(prompt,/excluded.php/);
 assert.equal(message.value,'draft');assert.equal(apply.disabled,true);
 resolve('feat: staged change');await wait();
 preview.value = 'feat: edited suggestion';
 apply.click();await wait();
 assert.equal(message.value,'feat: edited suggestion');assert.equal(updates,1);
 generate.click();await wait();resolve('another');await wait();
 message.value = 'new user draft';apply.click();await wait();
 assert.equal(message.value,'new user draft');assert.equal(dialog.open,true);
 controller.reset();generate.click();await wait();resolve('stale');await wait();
 token = 'index-2';apply.click();await wait();
 assert.equal(message.value,'new user draft');assert.match(dialog.textContent,/mudaram/);
 controller.reset();generate.click();await wait();controller.reset();resolve('late');await wait();
 assert.equal(dialog.open,false);assert.equal(message.value,'new user draft');
 for(const cleanup of cleanups.reverse())cleanup();
 await w.happyDOM.abort();await rm(folder,{recursive:true,force:true});
});
